impl State for GlowingOverscrollIndicatorState {
    type Widget = GlowingOverscrollIndicator;
    crate::state_accessors!();

    fn init_state(self: Handle<Self>, app: &mut App) {
        let widget = self.widget(app);
        let (color, axis) = (widget.color, widget.axis());
        let leading_controller =
            GlowController::new(app, TickerProviderRef::new(self), color, axis);
        let trailing_controller =
            GlowController::new(app, TickerProviderRef::new(self), color, axis);
        let listener: Rc<dyn Listenable> = Rc::new(waft_foundation::MergingListenable::new(vec![
            Some(Rc::new(leading_controller.clone())),
            Some(Rc::new(trailing_controller.clone())),
        ]));
        let state = app.get_mut(self);
        state.leading_controller = Some(leading_controller);
        state.trailing_controller = Some(trailing_controller);
        state.leading_and_trailing_listener = Some(listener);
    }

    fn did_update_widget(
        self: Handle<Self>,
        app: &mut App,
        old_widget: &GlowingOverscrollIndicator,
    ) {
        let widget = self.widget(app);
        let (color, axis) = (widget.color, widget.axis());
        if old_widget.color != color || old_widget.axis() != axis {
            let leading_controller = self.leading_controller(app);
            let trailing_controller = self.trailing_controller(app);
            leading_controller.set_color(app, color);
            leading_controller.set_axis(app, axis);
            trailing_controller.set_color(app, color);
            trailing_controller.set_axis(app, axis);
        }
    }

    fn activate(self: Handle<Self>, app: &mut App) {
        TickerProviderStateMixin::activate(self, app);
    }

    fn dispose(self: Handle<Self>, app: &mut App) {
        self.leading_controller(app).dispose(app);
        self.trailing_controller(app).dispose(app);
        TickerProviderStateMixin::dispose(self, app);
    }

    fn build(self: Handle<Self>, app: &mut App, _context: BuildContext) -> WidgetRef {
        let widget = self.widget(app);
        let state = app.get(self);
        let painter = GlowingOverscrollIndicatorPainter {
            leading_controller: if widget.show_leading {
                state.leading_controller.clone()
            } else {
                None
            },
            trailing_controller: if widget.show_trailing {
                state.trailing_controller.clone()
            } else {
                None
            },
            axis_direction: widget.axis_direction,
            repaint: state.leading_and_trailing_listener.clone(),
        };
        let mut child_boundary = RepaintBoundary::new();
        if let Some(child) = widget.child.clone() {
            child_boundary = child_boundary.child(child);
        }
        NotificationListener::<dyn ScrollNotification>::new(
            RepaintBoundary::new().child(
                CustomPaint::new()
                    .foreground_painter(painter)
                    .child(child_boundary),
            ),
        )
        .on_notification(
            move |app: &mut App, notification: &dyn ScrollNotification| {
                self.handle_scroll_notification(app, notification)
            },
        )
        .into_widget()
    }
}

// The Glow logic is a port of the logic in the following file:
// https://android.googlesource.com/platform/frameworks/base/+/main/core/java/android/widget/EdgeEffect.java
// as of December 2016.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum GlowState {
    Idle,
    Absorb,
    Pull,
    Recede,
}

/// Dart's `_GlowController`.
///
/// The fields Dart declares `late final` and builds after its status listener is on the glow
/// controller are `Option`s here, set in [`new`](Self::new) in Dart's order, so the status
/// listeners run in Dart's order.
struct GlowController {
    change_notifier: ChangeNotifierData,

    // animation of the main axis direction
    state: GlowState,
    glow_controller: Ref<AnimationController>,
    pull_recede_timer: Option<Timer>,
    paint_offset: f64,
    paint_offset_scroll_pixels: f64,

    // animation values
    decelerator: Option<Ref<CurvedAnimation>>,
    glow_opacity_tween: Ref<Tween<f64>>,
    glow_opacity: Option<AnimationRef<f64>>,
    glow_size_tween: Ref<Tween<f64>>,
    glow_size: Option<AnimationRef<f64>>,

    // animation of the cross axis position
    displacement_ticker: Option<Ref<Ticker>>,
    displacement_ticker_last_elapsed: Option<Duration>,
    displacement_target: f64,
    displacement: f64,

    // tracking the pull distance
    pull_distance: f64,

    color: Color,
    axis: Axis,
}

impl GlowController {
    const RECEDE_TIME: Duration = Duration::from_millis(600);
    const PULL_TIME: Duration = Duration::from_millis(167);
    const PULL_HOLD_TIME: Duration = Duration::from_millis(167);
    const PULL_DECAY_TIME: Duration = Duration::from_millis(2000);

    const MAX_OPACITY: f64 = 0.5;
    const PULL_OPACITY_GLOW_FACTOR: f64 = 0.8;
    const VELOCITY_GLOW_FACTOR: f64 = 0.00006;
    const SQRT3: f64 = 1.73205080757; // const math.sqrt(3)
    const WIDTH_TO_HEIGHT_FACTOR: f64 = (3.0 / 4.0) * (2.0 - GlowController::SQRT3);

    // absorbed velocities are clamped to the range MIN_VELOCITY..MAX_VELOCITY
    const MIN_VELOCITY: f64 = 100.0; // logical pixels per second
    const MAX_VELOCITY: f64 = 10000.0; // logical pixels per second

    /// Dart's `static final _crossAxisHalfTime`, a sixtieth of a second rounded to the
    /// microsecond.
    fn cross_axis_half_time() -> Duration {
        Duration::from_micros((1_000_000.0_f64 / 60.0).round() as u64)
    }

    fn new(
        app: &mut App,
        vsync: TickerProviderRef,
        color: Color,
        axis: Axis,
    ) -> Ref<GlowController> {
        let glow_controller = AnimationController::new(
            app,
            None,
            None,
            None,
            0.0,
            1.0,
            AnimationBehavior::Normal,
            vsync.clone(),
        );
        let glow_opacity_tween = Tween::new(app, Some(0.0), Some(0.0));
        let glow_size_tween = Tween::new(app, Some(0.0), Some(0.0));
        let this = app.create(GlowController {
            change_notifier: ChangeNotifierData::new(),
            state: GlowState::Idle,
            glow_controller: glow_controller.clone(),
            pull_recede_timer: None,
            paint_offset: 0.0,
            paint_offset_scroll_pixels: 0.0,
            decelerator: None,
            glow_opacity_tween: glow_opacity_tween.clone(),
            glow_opacity: None,
            glow_size_tween: glow_size_tween.clone(),
            glow_size: None,
            displacement_ticker: None,
            displacement_ticker_last_elapsed: None,
            displacement_target: 0.5,
            displacement: 0.5,
            pull_distance: 0.0,
            color,
            axis,
        });
        let handle = this.handle();
        glow_controller.view().add_status_listener(
            app,
            AnimationStatusListener::handle_method(handle, GlowController::change_phase),
        );
        let decelerator =
            CurvedAnimation::new(app, glow_controller.erase(), Curves::decelerate(), None);
        decelerator.add_listener(
            app,
            Listener::handle_method(handle, Handle::<GlowController>::notify_listeners),
        );
        let glow_opacity = decelerator.drive(app, glow_opacity_tween);
        let glow_size = decelerator.drive(app, glow_size_tween);
        let displacement_ticker = vsync.create_ticker(
            app,
            FrameCallback::handle_method(handle, GlowController::tick_displacement),
        );
        let controller = app.get_mut(&this);
        controller.decelerator = Some(decelerator);
        controller.glow_opacity = Some(glow_opacity);
        controller.glow_size = Some(glow_size);
        controller.displacement_ticker = Some(displacement_ticker);
        this
    }

    fn decelerator(self: Handle<Self>, app: &App) -> Handle<CurvedAnimation> {
        app.get(self)
            .decelerator
            .handle()
            .expect("set by the constructor")
    }

    fn glow_opacity(self: Handle<Self>, app: &App) -> AnyAnimation<f64> {
        app.get(self)
            .glow_opacity
            .handle()
            .expect("set by the constructor")
    }

    fn glow_size(self: Handle<Self>, app: &App) -> AnyAnimation<f64> {
        app.get(self)
            .glow_size
            .handle()
            .expect("set by the constructor")
    }

    fn displacement_ticker(self: Handle<Self>, app: &App) -> Handle<Ticker> {
        app.get(self)
            .displacement_ticker
            .handle()
            .expect("set by the constructor")
    }

    fn color(self: Handle<Self>, app: &App) -> Color {
        app.get(self).color
    }

    fn set_color(self: Handle<Self>, app: &mut App, value: Color) {
        if self.color(app) == value {
            return;
        }
        app.get_mut(self).color = value;
        self.notify_listeners(app);
    }

    fn axis(self: Handle<Self>, app: &App) -> Axis {
        app.get(self).axis
    }

    fn set_axis(self: Handle<Self>, app: &mut App, value: Axis) {
        if self.axis(app) == value {
            return;
        }
        app.get_mut(self).axis = value;
        self.notify_listeners(app);
    }

    fn cancel_pull_recede_timer(self: Handle<Self>, app: &mut App) {
        if let Some(timer) = app.get(self).pull_recede_timer {
            timer.cancel(app);
        }
    }

    fn dispose(self: Handle<Self>, app: &mut App) {
        app.get(self).glow_controller.dispose(app);
        self.decelerator(app).dispose(app);
        self.displacement_ticker(app).dispose(app);
        self.cancel_pull_recede_timer(app);
        ChangeNotifierData::dispose(app, self);
    }

    /// Handle a scroll slamming into the edge at a particular velocity.
    ///
    /// The velocity must be positive.
    fn absorb_impact(self: Handle<Self>, app: &mut App, velocity: f64) {
        debug_assert!(velocity >= 0.0);
        self.cancel_pull_recede_timer(app);
        app.get_mut(self).pull_recede_timer = None;
        let velocity = clamp_double(velocity, Self::MIN_VELOCITY, Self::MAX_VELOCITY);
        let glow_opacity_begin = if app.get(self).state == GlowState::Idle {
            0.3
        } else {
            self.glow_opacity(app).value(app)
        };
        let glow_opacity_tween = app.get(self).glow_opacity_tween.handle();
        glow_opacity_tween.set_begin(app, Some(glow_opacity_begin));
        glow_opacity_tween.set_end(
            app,
            Some(clamp_double(
                velocity * Self::VELOCITY_GLOW_FACTOR,
                glow_opacity_begin,
                Self::MAX_OPACITY,
            )),
        );
        let glow_size_tween = app.get(self).glow_size_tween.handle();
        let glow_size = self.glow_size(app).value(app);
        glow_size_tween.set_begin(app, Some(glow_size));
        glow_size_tween.set_end(
            app,
            Some(f64::min(0.025 + 7.5e-7 * velocity * velocity, 1.0)),
        );
        let glow_controller = app.get(self).glow_controller.handle();
        app.get_mut(glow_controller).duration = Some(Duration::from_millis(
            (0.15 + velocity * 0.02).round() as u64,
        ));
        glow_controller.forward(app, Some(0.0));
        let controller = app.get_mut(self);
        controller.displacement = 0.5;
        controller.state = GlowState::Absorb;
    }

    /// Handle a user-driven overscroll.
    ///
    /// The `overscroll` argument should be the scroll distance in logical pixels,
    /// the `extent` argument should be the total dimension of the viewport in the
    /// main axis in logical pixels, the `cross_axis_offset` argument should be the
    /// distance from the leading (left or top) edge of the cross axis of the
    /// viewport, and the `cross_extent` should be the size of the cross axis. For
    /// example, a pull of 50 pixels up the middle of a 200 pixel high and 100
    /// pixel wide vertical viewport should result in a call of `pull(50.0, 200.0,
    /// 50.0, 100.0)`. The `overscroll` value should be positive regardless of the
    /// direction.
    fn pull(
        self: Handle<Self>,
        app: &mut App,
        overscroll: f64,
        extent: f64,
        cross_axis_offset: f64,
        cross_extent: f64,
    ) {
        self.cancel_pull_recede_timer(app);
        // This factor is magic. Not clear why we need it to match Android.
        app.get_mut(self).pull_distance += overscroll / 200.0;
        // Dart reads each animation's value again once its tween's `begin` is set, and the
        // second read sees the new `begin`.
        let glow_opacity_tween = app.get(self).glow_opacity_tween.handle();
        let glow_opacity = self.glow_opacity(app).value(app);
        glow_opacity_tween.set_begin(app, Some(glow_opacity));
        let glow_opacity = self.glow_opacity(app).value(app);
        glow_opacity_tween.set_end(
            app,
            Some(f64::min(
                glow_opacity + overscroll / extent * Self::PULL_OPACITY_GLOW_FACTOR,
                Self::MAX_OPACITY,
            )),
        );
        let height = f64::min(extent, cross_extent * Self::WIDTH_TO_HEIGHT_FACTOR);
        let glow_size_tween = app.get(self).glow_size_tween.handle();
        let glow_size = self.glow_size(app).value(app);
        glow_size_tween.set_begin(app, Some(glow_size));
        let pull_distance = app.get(self).pull_distance;
        let glow_size = self.glow_size(app).value(app);
        glow_size_tween.set_end(
            app,
            Some(f64::max(
                1.0 - 1.0 / (0.7 * (pull_distance * height).sqrt()),
                glow_size,
            )),
        );
        app.get_mut(self).displacement_target = cross_axis_offset / cross_extent;
        let displacement_ticker = self.displacement_ticker(app);
        let controller = app.get(self);
        if controller.displacement_target != controller.displacement {
            if !displacement_ticker.is_ticking(app) {
                debug_assert!(app.get(self).displacement_ticker_last_elapsed.is_none());
                displacement_ticker.start(app);
            }
        } else {
            displacement_ticker.stop(app, false);
            app.get_mut(self).displacement_ticker_last_elapsed = None;
        }
        let glow_controller = app.get(self).glow_controller.handle();
        app.get_mut(glow_controller).duration = Some(Self::PULL_TIME);
        if app.get(self).state != GlowState::Pull {
            glow_controller.forward(app, Some(0.0));
            app.get_mut(self).state = GlowState::Pull;
        } else if !glow_controller.is_animating(app) {
            debug_assert!(glow_controller.value(app) == 1.0);
            self.notify_listeners(app);
        }
        let timer = Timer::new(
            app,
            Self::PULL_HOLD_TIME,
            Listener::new(move |app: &mut App| self.recede(app, Self::PULL_DECAY_TIME)),
        );
        app.get_mut(self).pull_recede_timer = Some(timer);
    }

    fn scroll_end(self: Handle<Self>, app: &mut App) {
        if app.get(self).state == GlowState::Pull {
            self.recede(app, Self::RECEDE_TIME);
        }
    }

    fn change_phase(self: Handle<Self>, app: &mut App, status: AnimationStatus) {
        if !status.is_completed() {
            return;
        }
        match app.get(self).state {
            GlowState::Absorb => self.recede(app, Self::RECEDE_TIME),
            GlowState::Recede => {
                let controller = app.get_mut(self);
                controller.state = GlowState::Idle;
                controller.pull_distance = 0.0;
            }
            GlowState::Pull | GlowState::Idle => {}
        }
    }

    fn recede(self: Handle<Self>, app: &mut App, duration: Duration) {
        let state = app.get(self).state;
        if state == GlowState::Recede || state == GlowState::Idle {
            return;
        }
        self.cancel_pull_recede_timer(app);
        app.get_mut(self).pull_recede_timer = None;
        let glow_opacity = self.glow_opacity(app).value(app);
        let glow_opacity_tween = app.get(self).glow_opacity_tween.handle();
        glow_opacity_tween.set_begin(app, Some(glow_opacity));
        glow_opacity_tween.set_end(app, Some(0.0));
        let glow_size = self.glow_size(app).value(app);
        let glow_size_tween = app.get(self).glow_size_tween.handle();
        glow_size_tween.set_begin(app, Some(glow_size));
        glow_size_tween.set_end(app, Some(0.0));
        let glow_controller = app.get(self).glow_controller.handle();
        app.get_mut(glow_controller).duration = Some(duration);
        glow_controller.forward(app, Some(0.0));
        app.get_mut(self).state = GlowState::Recede;
    }

    fn tick_displacement(self: Handle<Self>, app: &mut App, elapsed: Duration) {
        if let Some(last_elapsed) = app.get(self).displacement_ticker_last_elapsed {
            let t = (elapsed.as_micros() as i64 - last_elapsed.as_micros() as i64) as f64;
            let controller = app.get_mut(self);
            controller.displacement = controller.displacement_target
                - (controller.displacement_target - controller.displacement)
                    * 2.0_f64.powf(-t / Self::cross_axis_half_time().as_micros() as f64);
            self.notify_listeners(app);
        }
        let controller = app.get(self);
        if near_equal(
            Some(controller.displacement_target),
            Some(controller.displacement),
            Tolerance::DEFAULT_TOLERANCE.distance,
        ) {
            self.displacement_ticker(app).stop(app, false);
            app.get_mut(self).displacement_ticker_last_elapsed = None;
        } else {
            app.get_mut(self).displacement_ticker_last_elapsed = Some(elapsed);
        }
    }

    fn paint(self: Handle<Self>, app: &App, canvas: &mut Canvas, size: Size) {
        let glow_opacity = self.glow_opacity(app).value(app);
        if glow_opacity == 0.0 {
            return;
        }
        let controller = app.get(self);
        let base_glow_scale = if size.width() > size.height() {
            size.height() / size.width()
        } else {
            1.0
        };
        let radius = size.width() * 3.0 / 2.0;
        let height = f64::min(size.height(), size.width() * Self::WIDTH_TO_HEIGHT_FACTOR);
        let scale_y = self.glow_size(app).value(app) * base_glow_scale;
        let rect = Rect::from_ltwh(0.0, 0.0, size.width(), height);
        let center = Offset::new(
            (size.width() / 2.0) * (0.5 + controller.displacement),
            height - radius,
        );
        #[allow(deprecated)]
        let paint = Paint::from_color(controller.color.with_opacity(glow_opacity).into());
        canvas.save();
        canvas.translate(
            0.0,
            (controller.paint_offset + controller.paint_offset_scroll_pixels) as f32,
        );
        canvas.scale(1.0, scale_y as f32);
        canvas.clip_rect(rect, ClipOp::Intersect, true);
        canvas.draw_circle(center, radius as f32, &paint);
        canvas.restore();
    }
}

