/// Dart's `_GlowingOverscrollIndicatorState`.
pub struct GlowingOverscrollIndicatorState {
    state: StateData<GlowingOverscrollIndicator>,
    ticker_provider: TickerProviderStateMixinData,
    leading_controller: Option<Ref<GlowController>>,
    trailing_controller: Option<Ref<GlowController>>,
    leading_and_trailing_listener: Option<Rc<dyn Listenable>>,
    /// Dart's `Map<bool, bool> _accepted`, indexed by `is_leading as usize`.
    accepted: [bool; 2],
}

impl GlowingOverscrollIndicatorState {
    fn leading_controller(self: Handle<Self>, app: &App) -> Handle<GlowController> {
        app.get(self)
            .leading_controller
            .handle()
            .expect("the controllers are made in init_state")
    }

    fn trailing_controller(self: Handle<Self>, app: &App) -> Handle<GlowController> {
        app.get(self)
            .trailing_controller
            .handle()
            .expect("the controllers are made in init_state")
    }

    fn handle_scroll_notification(
        self: Handle<Self>,
        app: &mut App,
        notification: &dyn ScrollNotification,
    ) -> bool {
        let widget = self.widget(app);
        let notification_predicate = Rc::clone(&widget.notification_predicate);
        let axis = widget.axis();
        if !notification_predicate(notification) {
            return false;
        }
        let metrics = Rc::clone(notification.metrics());
        if metrics.axis() != axis {
            // This widget is explicitly configured to one axis. If a notification
            // from a different axis bubbles up, do nothing.
            return false;
        }

        let leading_controller = self.leading_controller(app);
        let trailing_controller = self.trailing_controller(app);

        // Update the paint offset with the current scroll position. This makes
        // sure that the glow effect correctly scrolls in line with the current
        // scroll, e.g. when scrolling in the opposite direction again to hide
        // the glow. Otherwise, the glow would always stay in a fixed position,
        // even if the top of the content already scrolled away.
        // For example (CustomScrollView with sliver before center), the scroll
        // extent is [-200.0, 300.0], scroll in the opposite direction with 10.0 pixels
        // before glow disappears, so the current pixels is -190.0,
        // in this case, we should move the glow up 10.0 pixels and should not
        // overflow the scrollable widget's edge. https://github.com/flutter/flutter/issues/64149.
        let leading = app.get_mut(leading_controller);
        leading.paint_offset_scroll_pixels = -f64::min(
            metrics.pixels() - metrics.min_scroll_extent(),
            leading.paint_offset,
        );
        let trailing = app.get_mut(trailing_controller);
        trailing.paint_offset_scroll_pixels = -f64::min(
            metrics.max_scroll_extent() - metrics.pixels(),
            trailing.paint_offset,
        );

        let any = notification.as_any();
        if let Some(notification) = any.downcast_ref::<OverscrollNotification>() {
            let controller = if notification.overscroll < 0.0 {
                Some(leading_controller)
            } else if notification.overscroll > 0.0 {
                Some(trailing_controller)
            } else {
                debug_assert!(false);
                None
            };
            let is_leading = controller == Some(leading_controller);
            // Dart's `_lastNotificationType is! OverscrollNotification` (see the module doc).
            let confirmation_notification = OverscrollIndicatorNotification::new(is_leading);
            confirmation_notification.dispatch(app, Some(self.context(app)));
            let accepted = confirmation_notification.accepted.get();
            app.get_mut(self).accepted[is_leading as usize] = accepted;
            if accepted {
                let controller = controller.expect("an overscroll is on one side");
                app.get_mut(controller).paint_offset = confirmation_notification.paint_offset.get();
            }
            debug_assert!(controller.is_some());
            if app.get(self).accepted[is_leading as usize] {
                let controller = controller.expect("an overscroll is on one side");
                if notification.velocity != 0.0 {
                    debug_assert!(notification.drag_details.is_none());
                    controller.absorb_impact(app, notification.velocity.abs());
                } else {
                    debug_assert!(notification.overscroll != 0.0);
                    if let Some(drag_details) = &notification.drag_details {
                        let renderer = notification
                            .context()
                            .expect("a scroll notification carries the scrollable's context")
                            .find_render_object(app)
                            .expect("the scrollable has a render object")
                            .as_box()
                            .expect("the scrollable's render object is a box");
                        debug_assert!(renderer.has_size(app));
                        let size = renderer.size(app);
                        let position =
                            renderer.global_to_local(app, drag_details.global_position, None);
                        match notification.metrics().axis() {
                            Axis::Horizontal => controller.pull(
                                app,
                                notification.overscroll.abs(),
                                size.width(),
                                clamp_double(position.dy(), 0.0, size.height()),
                                size.height(),
                            ),
                            Axis::Vertical => controller.pull(
                                app,
                                notification.overscroll.abs(),
                                size.height(),
                                clamp_double(position.dx(), 0.0, size.width()),
                                size.width(),
                            ),
                        }
                    }
                }
            }
        } else if any
            .downcast_ref::<ScrollEndNotification>()
            .is_some_and(|notification| notification.drag_details.is_some())
            || any
                .downcast_ref::<ScrollUpdateNotification>()
                .is_some_and(|notification| notification.drag_details.is_some())
        {
            leading_controller.scroll_end(app);
            trailing_controller.scroll_end(app);
        }
        false
    }
}

