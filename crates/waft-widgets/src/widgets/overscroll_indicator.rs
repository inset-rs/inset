/// Dart's `_GlowingOverscrollIndicatorPainter`.
struct GlowingOverscrollIndicatorPainter {
    /// The controller for the overscroll glow on the side with negative scroll offsets.
    ///
    /// For a vertical downwards viewport, this is the top side.
    leading_controller: Option<Ref<GlowController>>,

    /// The controller for the overscroll glow on the side with positive scroll offsets.
    ///
    /// For a vertical downwards viewport, this is the bottom side.
    trailing_controller: Option<Ref<GlowController>>,

    /// The direction of the viewport.
    axis_direction: AxisDirection,

    /// Dart's `super.repaint`.
    repaint: Option<Rc<dyn Listenable>>,
}

impl GlowingOverscrollIndicatorPainter {
    const PI_OVER_2: f64 = std::f64::consts::PI / 2.0;

    fn paint_side(
        &self,
        app: &App,
        canvas: &mut Canvas,
        size: Size,
        controller: Option<Handle<GlowController>>,
        axis_direction: AxisDirection,
        growth_direction: GrowthDirection,
    ) {
        let Some(controller) = controller else {
            return;
        };
        match apply_growth_direction_to_axis_direction(axis_direction, growth_direction) {
            AxisDirection::Up => controller.paint(app, canvas, size),
            AxisDirection::Down => {
                canvas.save();
                canvas.translate(0.0, size.height() as f32);
                canvas.scale(1.0, -1.0);
                controller.paint(app, canvas, size);
                canvas.restore();
            }
            AxisDirection::Left => {
                canvas.save();
                canvas.rotate(Self::PI_OVER_2 as f32);
                canvas.scale(1.0, -1.0);
                controller.paint(app, canvas, Size::new(size.height(), size.width()));
                canvas.restore();
            }
            AxisDirection::Right => {
                canvas.save();
                canvas.translate(size.width() as f32, 0.0);
                canvas.rotate(Self::PI_OVER_2 as f32);
                controller.paint(app, canvas, Size::new(size.height(), size.width()));
                canvas.restore();
            }
        }
    }
}

impl CustomPainter for GlowingOverscrollIndicatorPainter {
    fn repaint(&self) -> Option<&Rc<dyn Listenable>> {
        self.repaint.as_ref()
    }

    fn paint(&self, app: &mut App, canvas: &mut Canvas, size: Size) {
        self.paint_side(
            app,
            canvas,
            size,
            self.leading_controller.handle(),
            self.axis_direction,
            GrowthDirection::Reverse,
        );
        self.paint_side(
            app,
            canvas,
            size,
            self.trailing_controller.handle(),
            self.axis_direction,
            GrowthDirection::Forward,
        );
    }

    fn should_repaint(&self, _app: &App, old_delegate: &dyn CustomPainter) -> bool {
        let old_delegate = old_delegate
            .as_any()
            .downcast_ref::<GlowingOverscrollIndicatorPainter>()
            .expect("Dart's covariant parameter");
        old_delegate.leading_controller != self.leading_controller
            || old_delegate.trailing_controller != self.trailing_controller
    }

    fn as_any(&self) -> &dyn std::any::Any {
        self
    }
}

impl Debug for GlowingOverscrollIndicatorPainter {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "_GlowingOverscrollIndicatorPainter({:?}, {:?})",
            self.leading_controller, self.trailing_controller
        )
    }
}

/// A Material Design visual indication that a scroll view has overscrolled.
///
/// A [`StretchingOverscrollIndicator`] listens for [`ScrollNotification`]s in order
/// to stretch the content of the `Scrollable`. These notifications are typically
/// generated by a `ScrollView`, such as a `ListView` or a `GridView`.
///
/// When triggered, the [`StretchingOverscrollIndicator`] generates an
/// [`OverscrollIndicatorNotification`] before showing an overscroll indication.
/// To prevent the indicator from showing the indication, call
/// [`OverscrollIndicatorNotification::disallow_indicator`] on the notification.
///
/// Created by `MaterialScrollBehavior::build_overscroll_indicator` on platforms
/// (e.g., Android) that commonly use this type of overscroll indication when
/// `ThemeData::use_material3` is true. Otherwise, when `ThemeData::use_material3`
/// is false, a [`GlowingOverscrollIndicator`] is used instead.
///
/// See also:
///
///  * [`OverscrollIndicatorNotification`], which can be used to prevent the
///    stretch effect from being applied at all.
///  * [`NotificationListener`], to listen for the
///    [`OverscrollIndicatorNotification`].
///  * [`GlowingOverscrollIndicator`], the default overscroll indicator for
///    `TargetPlatform::Android` and `TargetPlatform::Fuchsia`.
pub struct StretchingOverscrollIndicator {
    pub key: Option<KeyRef>,

    /// The direction of positive scroll offsets in the `Scrollable` whose
    /// overscrolls are to be visualized.
    pub axis_direction: AxisDirection,

    /// A check that specifies whether a [`ScrollNotification`] should be
    /// handled by this widget.
    ///
    /// By default, checks whether `notification.depth() == 0`. Set it to something
    /// else for more complicated layouts, such as nested `ScrollView`s.
    pub notification_predicate: ScrollNotificationPredicate,

    /// The content will be clipped (or not) according to this option.
    ///
    /// Defaults to [`Clip::HardEdge`].
    pub clip_behavior: Clip,

    /// The widget below this widget in the tree.
    ///
    /// The overscroll indicator will apply a stretch effect to this child. This
    /// child (and its subtree) should include a source of [`ScrollNotification`]
    /// notifications.
    pub child: Option<WidgetRef>,
}

impl StretchingOverscrollIndicator {
    /// Creates a visual indication that a scroll view has overscrolled by
    /// applying a stretch transformation to the content.
    ///
    /// In order for this widget to display an overscroll indication, the [`child`](Self::child)
    /// widget must contain a widget that generates a [`ScrollNotification`], such
    /// as a `ListView` or a `GridView`.
    pub fn new(axis_direction: AxisDirection) -> StretchingOverscrollIndicator {
        StretchingOverscrollIndicator {
            key: None,
            axis_direction,
            notification_predicate: Rc::new(default_scroll_notification_predicate),
            clip_behavior: Clip::HardEdge,
            child: None,
        }
    }

    /// Dart `StretchingOverscrollIndicator(key:)`.
    pub fn key(mut self, key: KeyRef) -> StretchingOverscrollIndicator {
        self.key = Some(key);
        self
    }

    /// Dart `StretchingOverscrollIndicator(notificationPredicate:)`.
    pub fn notification_predicate(
        mut self,
        notification_predicate: ScrollNotificationPredicate,
    ) -> StretchingOverscrollIndicator {
        self.notification_predicate = notification_predicate;
        self
    }

    /// Dart `StretchingOverscrollIndicator(clipBehavior:)`.
    pub fn clip_behavior(mut self, clip_behavior: Clip) -> StretchingOverscrollIndicator {
        self.clip_behavior = clip_behavior;
        self
    }

    /// Dart `StretchingOverscrollIndicator(child:)`.
    pub fn child<K>(mut self, child: impl IntoWidget<K>) -> StretchingOverscrollIndicator {
        self.child = Some(child.into_widget());
        self
    }

    /// The axis along which scrolling occurs in the `Scrollable` whose
    /// overscrolls are to be visualized.
    pub fn axis(&self) -> Axis {
        axis_direction_to_axis(self.axis_direction)
    }
}

