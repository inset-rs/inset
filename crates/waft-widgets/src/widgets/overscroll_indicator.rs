    /// A listener that counts the confirmations and disallows them while `disallow` is set.
    fn counting_listener(
        child: WidgetRef,
        count: &Rc<Cell<u32>>,
        disallow: &Rc<Cell<bool>>,
    ) -> WidgetRef {
        let count = Rc::clone(count);
        let disallow = Rc::clone(disallow);
        NotificationListener::<OverscrollIndicatorNotification>::new(child)
            .on_notification(move |_app, notification| {
                if disallow.get() {
                    notification.disallow_indicator();
                }
                count.set(count.get() + 1);
                false
            })
            .into_widget()
    }

