/// Dart's `_StretchingOverscrollIndicatorState`.
pub struct StretchingOverscrollIndicatorState {
    state: StateData<StretchingOverscrollIndicator>,
    ticker_provider: TickerProviderStateMixinData,
    /// Dart's `late final _stretchController`, made on first use, with the `Listenable` the
    /// builder listens to, made once so a rebuild hands the builder the same one.
    stretch_controller: Option<(Ref<StretchController>, Rc<dyn Listenable>)>,
    /// The metrics of Dart's `_lastOverscrollNotification`, the one member of it `build`
    /// reads.
    last_overscroll_notification_metrics:
        Option<Rc<dyn crate::widgets::scroll_metrics::ScrollMetrics>>,
    total_overscroll: f64,
    accepted: bool,
}

impl StretchingOverscrollIndicatorState {
    fn stretch_controller(self: Handle<Self>, app: &mut App) -> Handle<StretchController> {
        self.stretch_listenable_controller(app).0
    }

    fn stretch_listenable_controller(
        self: Handle<Self>,
        app: &mut App,
    ) -> (Handle<StretchController>, Rc<dyn Listenable>) {
        if let Some((controller, listenable)) = &app.get(self).stretch_controller {
            return (controller.handle(), Rc::clone(listenable));
        }
        let controller = StretchController::new(app, TickerProviderRef::new(self));
        let handle = controller.handle();
        let listenable: Rc<dyn Listenable> = Rc::new(controller.clone());
        app.get_mut(self).stretch_controller = Some((controller, Rc::clone(&listenable)));
        (handle, listenable)
    }

    fn handle_scroll_notification(
        self: Handle<Self>,
        app: &mut App,
        notification: &dyn ScrollNotification,
    ) -> bool {
        let widget = self.widget(app);
        let notification_predicate = Rc::clone(&widget.notification_predicate);
        let axis = widget.axis();
        if !notification_predicate(notification) {
            return false;
        }
        if notification.metrics().axis() != axis {
            // This widget is explicitly configured to one axis. If a notification
            // from a different axis bubbles up, do nothing.
            return false;
        }
        let any = notification.as_any();
        if any.is::<ScrollStartNotification>() {
            let state = app.get_mut(self);
            state.accepted = true;
            state.total_overscroll = 0.0;
        } else if let Some(notification) = any.downcast_ref::<OverscrollNotification>() {
            app.get_mut(self).last_overscroll_notification_metrics =
                Some(Rc::clone(notification.metrics()));
            // Dart's `_lastNotification.runtimeType is! OverscrollNotification` (see the
            // module doc).
            let confirmation_notification =
                OverscrollIndicatorNotification::new(notification.overscroll < 0.0);
            confirmation_notification.dispatch(app, Some(self.context(app)));
            app.get_mut(self).accepted = confirmation_notification.accepted.get();

            if app.get(self).accepted {
                app.get_mut(self).total_overscroll += notification.overscroll;

                if notification.velocity != 0.0 {
                    debug_assert!(notification.drag_details.is_none());
                    self.stretch_controller(app)
                        .absorb_impact(app, notification.velocity);
                } else {
                    debug_assert!(notification.overscroll != 0.0);
                    if notification.drag_details.is_some() {
                        // We clamp the overscroll amount relative to the length of the viewport,
                        // which is the furthest distance a single pointer could pull on the
                        // screen. This is because more than one pointer will multiply the
                        // amount of overscroll - https://github.com/flutter/flutter/issues/11884

                        let viewport_dimension = notification.metrics().viewport_dimension();
                        let distance_for_pull = app.get(self).total_overscroll / viewport_dimension;
                        let clamped_overscroll = clamp_double(distance_for_pull, -1.0, 1.0);
                        self.stretch_controller(app).pull(app, clamped_overscroll);
                    }
                }
            }
        } else if let Some(notification) = any.downcast_ref::<ScrollEndNotification>() {
            let mut velocity = match axis {
                Axis::Vertical => notification
                    .drag_details
                    .as_ref()
                    .map_or(0.0, |details| details.velocity.pixels_per_second.dy()),
                Axis::Horizontal => notification
                    .drag_details
                    .as_ref()
                    .map_or(0.0, |details| details.velocity.pixels_per_second.dx()),
            };

            // Reverse axis directions report dragDetails velocity in
            // the opposite screen coordinate, so the value must be inverted.
            if matches!(
                notification.metrics().axis_direction(),
                AxisDirection::Left | AxisDirection::Up
            ) {
                velocity = -velocity;
            }

            // Since the overscrolling ended, we reset the total overscroll amount.
            app.get_mut(self).total_overscroll = 0.0;
            if app.get(self).accepted {
                self.stretch_controller(app).scroll_end(app, velocity);
            }
        } else if any.is::<ScrollUpdateNotification>() {
            app.get_mut(self).total_overscroll = 0.0;
            self.stretch_controller(app).scroll_end(app, 0.0);
        }
        false
    }

    /// The body of the `AnimatedBuilder` Dart's `build` returns.
    fn build_stretch(self: Handle<Self>, app: &mut App, context: BuildContext) -> WidgetRef {
        let stretch = self.stretch_controller(app).overscroll(app);
        let widget = self.widget(app);
        let (axis, axis_direction, clip_behavior) =
            (widget.axis(), widget.axis_direction, widget.clip_behavior);
        let child = widget
            .child
            .clone()
            .unwrap_or_else(|| SizedBox::shrink().into_widget());

        let main_axis_size = match axis {
            Axis::Horizontal => MediaQuery::width_of(app, context),
            Axis::Vertical => MediaQuery::height_of(app, context),
        };

        let viewport_dimension = app
            .get(self)
            .last_overscroll_notification_metrics
            .as_ref()
            .map_or(main_axis_size, |metrics| metrics.viewport_dimension());

        let mut overscroll = -stretch;

        // Adjust overscroll for reverse scroll directions.
        if axis_direction == AxisDirection::Up || axis_direction == AxisDirection::Left {
            overscroll = -overscroll;
        }

        let transform = StretchEffect::new(axis, child).stretch_strength(overscroll);

        // Only clip if the viewport dimension is smaller than that of the
        // screen size in the main axis. If the viewport takes up the whole
        // screen, overflow from transforming the viewport is irrelevant.
        ClipRect::new()
            .clip_behavior(if stretch != 0.0 && viewport_dimension != main_axis_size {
                clip_behavior
            } else {
                Clip::None
            })
            .child(transform)
            .into_widget()
    }
}

