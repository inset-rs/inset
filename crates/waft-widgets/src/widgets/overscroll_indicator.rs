/// Dart's `_StretchController`, a `Listenable` that forwards its listeners to the notifier
/// of its [`overscroll`](Self::overscroll).
struct StretchController {
    vsync: TickerProviderRef,
    controller: Option<Ref<AnimationController>>,

    /// Manages and notifies changes to the current [`overscroll`](Self::overscroll) value.
    overscroll_notifier: Ref<ValueNotifier<f64>>,

    /// Stores the `overscroll` value from an ongoing animation at the precise
    /// moment it is interrupted by a new `pull()` gesture.
    ///
    /// When `pull()` is called while an animation (triggered by `absorb_impact`
    /// or `scroll_end`) is active, this field captures the animation's current
    /// `controller.value` (which represents the overscroll amount) immediately
    /// before the animation controller is disposed.
    ///
    /// This captured value is then added to the overscroll amount calculated
    /// by the `pull()` method. The primary purpose is to create a smoother
    /// visual transition from an animated overscroll state to a direct,
    /// user-driven pull, minimizing any abrupt visual "jumps" in the
    /// stretch effect.
    ///
    /// It is reset to `0.0` when an animation completes naturally via `animate()`
    /// or when a new pull starts without a preceding active animation.
    interrupted_overscroll: f64,
}

impl StretchController {
    // Constants from Android.
    const EXPONENTIAL_SCALAR: f64 = std::f64::consts::E / 0.33;
    const STRETCH_INTENSITY: f64 = 0.016;

    const MIN_OVERSCROLL: f64 = -1.0;
    const MAX_OVERSCROLL: f64 = 1.0;

    /// A fraction used to adjust the input velocity, measured in pixels,
    /// to a value between -1 and 1 when gesture fling.
    const FLING_VELOCITY_FRICTION: f64 = 1.0 / 6000.0;

    /// A fraction used to scale the absorbed impact velocity,
    /// converting raw velocity into a normalized value for simulation.
    const ABSORB_IMPACT_VELOCITY_FRICTION: f64 = 1.0 / 3000.0;

    /// The maximum velocity allowed for a fling after scaling
    /// to prevent applying an excessive stretch effect.
    const MAX_FLING_VELOCITY: f64 = 0.5;

    /// The maximum velocity allowed when absorbing an impact,
    /// ensuring the stretch effect does not exceed a reasonable limit.
    const MAX_ABSORB_IMPACT_VELOCITY: f64 = 1.25;

    // Physical constants ported directly from Android's EdgeEffect.java.
    //
    // Android's EdgeEffect.java:
    // https://cs.android.com/android/platform/superproject/main/+/main:frameworks/base/core/java/android/widget/EdgeEffect.java
    const K_NATURAL_FREQUENCY: f64 = 24.657;
    const K_DAMPING_RATIO: f64 = 0.98;

    /// A correction factor applied to the simulation time.
    ///
    /// The physical constants `K_NATURAL_FREQUENCY` and `K_DAMPING_RATIO` were ported
    /// directly from Android's `EdgeEffect.java` source. However, using these
    /// constants as-is resulted in an animation that was noticeably faster than
    /// the native Android behavior. The underlying reason for this discrepancy is
    /// unknown.
    ///
    /// This factor, determined by visual comparison ("eyeballing") to match the
    /// platform's timing, is applied to the elapsed time `t` to slow down the
    /// simulation.
    ///
    /// Based on the damped harmonic oscillator equations, an alternative,
    /// mathematically equivalent, approach would be to multiply both the
    /// `K_NATURAL_FREQUENCY` and the initial velocity by this same factor,
    /// rather than scaling the time input.
    const K_TIME_CORRECTION_FACTOR: f64 = 0.8;

    /// Stiffness coefficient for the spring, derived from the natural frequency.
    ///
    /// Calculated as `K_STIFFNESS = K_NATURAL_FREQUENCY^2`, this is the baseline
    /// spring constant used in the damped harmonic oscillator model.
    const K_STIFFNESS: f64 = Self::K_NATURAL_FREQUENCY * Self::K_NATURAL_FREQUENCY;

    /// Spring description representing the stretch behavior of the edge effect.
    ///
    /// This [`SpringDescription`] is used to simulate the overscroll stretch.
    /// The spring has a mass of 1, a stiffness adjusted by the
    /// [`K_TIME_CORRECTION_FACTOR`](Self::K_TIME_CORRECTION_FACTOR) squared to match
    /// platform timing, and a damping ratio corresponding to Android's native `EdgeEffect`.
    fn stretch_spring_description() -> SpringDescription {
        SpringDescription::with_damping_ratio_value(
            1.0,
            Self::K_STIFFNESS * Self::K_TIME_CORRECTION_FACTOR * Self::K_TIME_CORRECTION_FACTOR,
            Self::K_DAMPING_RATIO,
        )
    }

    fn new(app: &mut App, vsync: TickerProviderRef) -> Ref<StretchController> {
        let overscroll_notifier = app.create(ValueNotifier::new(0.0));
        app.create(StretchController {
            vsync,
            controller: None,
            overscroll_notifier,
            interrupted_overscroll: 0.0,
        })
    }

    fn overscroll(self: Handle<Self>, app: &App) -> f64 {
        *app.get(&app.get(self).overscroll_notifier).value()
    }

    fn set_overscroll(self: Handle<Self>, app: &mut App, new_value: f64) {
        let notifier = app.get(self).overscroll_notifier.handle();
        notifier.set_value(
            app,
            clamp_double(new_value, Self::MIN_OVERSCROLL, Self::MAX_OVERSCROLL),
        );
    }

    /// Creates a stretching-only [`Simulation`] ported from Android 12.
    fn create_stretch_simulation(self: Handle<Self>, app: &App, velocity: f64) -> SpringSimulation {
        SpringSimulation::new(
            Self::stretch_spring_description(),
            self.overscroll(app),
            0.0,
            velocity * Self::K_TIME_CORRECTION_FACTOR,
        )
    }

    /// Handle a fling to the edge of the viewport at a particular velocity.
    ///
    /// The velocity must be positive.
    fn absorb_impact(self: Handle<Self>, app: &mut App, velocity: f64) {
        if velocity == 0.0 {
            return;
        }
        let scaled_velocity = clamp_double(
            velocity * Self::ABSORB_IMPACT_VELOCITY_FRICTION,
            -Self::MAX_ABSORB_IMPACT_VELOCITY,
            Self::MAX_ABSORB_IMPACT_VELOCITY,
        );

        let simulation = self.create_stretch_simulation(app, scaled_velocity);
        self.animate(app, Box::new(simulation));
    }

    /// Called when the overscroll ends to trigger a fling animation if needed.
    fn scroll_end(self: Handle<Self>, app: &mut App, velocity: f64) {
        if velocity == 0.0 && self.overscroll(app) == 0.0 {
            return;
        }
        let scaled_velocity = clamp_double(
            -(velocity * Self::FLING_VELOCITY_FRICTION),
            -Self::MAX_FLING_VELOCITY,
            Self::MAX_FLING_VELOCITY,
        );

        if app.get(self).controller.is_none() {
            let simulation = self.create_stretch_simulation(app, scaled_velocity);
            self.animate(app, Box::new(simulation));
        }
    }

    /// Starts a new animation using the given `simulation`.
    ///
    /// Disposes any existing animation controller before starting a new one.
    /// Updates the [`overscroll`](Self::overscroll) value on each animation frame.
    /// Automatically disposes the controller when the animation completes.
    fn animate(self: Handle<Self>, app: &mut App, simulation: Box<dyn Simulation>) {
        let vsync = app.get(self).vsync.clone();
        let controller = AnimationController::unbounded(
            app,
            0.0,
            None,
            None,
            AnimationBehavior::Preserve,
            vsync,
        );
        controller.view().add_listener(
            app,
            Listener::new(move |app: &mut App| {
                let new_overscroll = app
                    .get(self)
                    .controller
                    .handle()
                    .map_or(0.0, |controller| controller.value(app));
                self.set_overscroll(app, new_overscroll);
            }),
        );
        // The completion is the controller's own: it names the controller without keeping it.
        let handle = controller.handle();
        controller.animate_with(app, simulation).when_complete(
            app,
            Listener::new(move |app: &mut App| {
                let controller = handle;
                // Only clean up if this controller is still the active one. A later
                // pull(), animate(), or dispose() may have already replaced and disposed
                // it, in which case that path owns the cleanup and this stale completion
                // callback must not touch the shared state (or double dispose the
                // controller).
                if app.get(self).controller.handle() == Some(controller) {
                    self.set_overscroll(app, 0.0);
                    app.get_mut(self).interrupted_overscroll = 0.0;
                    controller.dispose(app);
                    app.get_mut(self).controller = None;
                }
            }),
        );

        if let Some(old_controller) = app.get(self).controller.handle() {
            old_controller.dispose(app);
        }
        app.get_mut(self).controller = Some(controller);
    }

    /// Handle a user-driven overscroll.
    ///
    /// The `normalized_overscroll` argument should be the scroll distance in
    /// logical pixels, divided by the extent of the viewport in the main axis.
    fn pull(self: Handle<Self>, app: &mut App, normalized_overscroll: f64) {
        if let Some(controller) = app.get(self).controller.handle() {
            app.get_mut(self).interrupted_overscroll = controller.value(app);
            controller.dispose(app);
            app.get_mut(self).controller = None;
        }

        let pull_distance = normalized_overscroll;
        let abs_distance = pull_distance.abs();
        let linear_intensity = Self::STRETCH_INTENSITY * abs_distance;
        let exponential_intensity =
            Self::STRETCH_INTENSITY * (1.0 - (-abs_distance * Self::EXPONENTIAL_SCALAR).exp());

        // Maintain sign of overscroll for direction; Dart's `double.sign` is zero for zero,
        // where `f64::signum` is one.
        let direction_sign = if pull_distance > 0.0 {
            1.0
        } else if pull_distance < 0.0 {
            -1.0
        } else {
            pull_distance
        };
        let new_overscroll = direction_sign * (linear_intensity + exponential_intensity);
        let interrupted_overscroll = app.get(self).interrupted_overscroll;
        self.set_overscroll(app, new_overscroll + interrupted_overscroll);
    }

    fn dispose(self: Handle<Self>, app: &mut App) {
        if let Some(controller) = app.get_mut(self).controller.take() {
            controller.dispose(app);
        }
        let notifier = app.get(self).overscroll_notifier.handle();
        notifier.dispose(app);
    }
}

impl ListenableObject for StretchController {
    fn add_listener(self: Handle<Self>, app: &mut App, listener: Listener) {
        let notifier = app.get(self).overscroll_notifier.handle();
        notifier.add_listener(app, listener);
    }

    fn remove_listener(self: Handle<Self>, app: &mut App, listener: &Listener) {
        let notifier = app.get(self).overscroll_notifier.handle();
        notifier.remove_listener(app, listener);
    }
}

impl Debug for StretchController {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("_StretchController()")
    }
}

/// A notification that either a [`GlowingOverscrollIndicator`] or a
/// [`StretchingOverscrollIndicator`] will start showing an overscroll indication.
///
/// To prevent the indicator from showing the indication, call
/// [`disallow_indicator`](Self::disallow_indicator) on the notification.
///
/// A listener writes [`paint_offset`](Self::paint_offset) and
/// [`accepted`](Self::accepted) through a shared reference, as the notification bubbles as
/// `&dyn Notification`; the indicator reads them back once the dispatch returns.
///
/// See also:
///
///  * [`GlowingOverscrollIndicator`], which generates this type of notification
///    by painting an indicator over the child content.
///  * [`StretchingOverscrollIndicator`], which generates this type of
///    notification by applying a stretch transformation to the child content.
pub struct OverscrollIndicatorNotification {
    viewport_notification: ViewportNotificationData,

    /// Whether the indication will be shown on the leading edge of the scroll
    /// view.
    pub leading: bool,

    /// Controls at which offset a [`GlowingOverscrollIndicator`] draws.
    ///
    /// A positive offset will move the glow away from its edge,
    /// i.e. for a vertical, [`leading`](Self::leading) indicator, a
    /// [`paint_offset`](Self::paint_offset) of 100.0 will draw the indicator 100.0 pixels
    /// from the top of the edge. For a vertical indicator with [`leading`](Self::leading)
    /// set to `false`, a [`paint_offset`](Self::paint_offset) of 100.0 will draw the indicator
    /// 100.0 pixels from the bottom instead.
    ///
    /// A negative [`paint_offset`](Self::paint_offset) is generally not useful, since the
    /// glow will be clipped.
    ///
    /// This has no effect on a [`StretchingOverscrollIndicator`].
    pub paint_offset: Cell<f64>,

    /// Whether the current overscroll event will allow for the indicator to be
    /// shown.
    ///
    /// Calling [`disallow_indicator`](Self::disallow_indicator) sets this to false,
    /// preventing the over scroll indicator from showing.
    ///
    /// Defaults to true.
    pub accepted: Cell<bool>,
}

impl OverscrollIndicatorNotification {
    /// Creates a notification that an [`GlowingOverscrollIndicator`] or a
    /// [`StretchingOverscrollIndicator`] will start showing an overscroll indication.
    pub fn new(leading: bool) -> OverscrollIndicatorNotification {
        OverscrollIndicatorNotification {
            viewport_notification: ViewportNotificationData::new(),
            leading,
            paint_offset: Cell::new(0.0),
            accepted: Cell::new(true),
        }
    }

    /// Call this method if the overscroll indicator should be prevented.
    pub fn disallow_indicator(&self) {
        self.accepted.set(false);
    }
}

impl Notification for OverscrollIndicatorNotification {
    fn as_any(&self) -> &dyn std::any::Any {
        self
    }

    fn viewport_depth(&self) -> Option<&Cell<u32>> {
        Some(self.viewport_notification.depth_cell())
    }
}

impl ViewportNotificationMixin for OverscrollIndicatorNotification {
    fn viewport_notification_data(&self) -> &ViewportNotificationData {
        &self.viewport_notification
    }
}

impl Debug for OverscrollIndicatorNotification {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut description = Vec::new();
        ViewportNotificationMixin::debug_fill_description(self, &mut description);
        description.push(format!(
            "side: {}",
            if self.leading {
                "leading edge"
            } else {
                "trailing edge"
            }
        ));
        write!(
            f,
            "OverscrollIndicatorNotification({})",
            description.join(", ")
        )
    }
}

