    /// `TestScrollBehavior2` (blue) and `TestScrollBehaviorNoGlow` (zero): a glow of `COLOR`,
    /// or none. Each is a type of its own, as Dart's three classes are, so swapping one for
    /// another rebuilds the scrollables under it.
    #[derive(Debug)]
    struct TestScrollBehavior<const COLOR: u32>;

    impl<const COLOR: u32> ScrollBehavior for TestScrollBehavior<COLOR> {
        fn as_any(&self) -> &dyn std::any::Any {
            self
        }

        fn build_overscroll_indicator(
            &self,
            _app: &mut App,
            _context: BuildContext,
            child: WidgetRef,
            details: &ScrollableDetails,
        ) -> WidgetRef {
            if COLOR == 0 {
                return child;
            }
            GlowingOverscrollIndicator::new(details.direction, Color::new(COLOR))
                .child(child)
                .into_widget()
        }
    }

    fn behavior<const COLOR: u32>() -> ScrollBehaviorRef {
        ScrollBehaviorRef::new(TestScrollBehavior::<COLOR>)
    }

    /// A listener that sets `paint_offset` on the confirmations `side` picks.
    fn paint_offset_listener(
        child: WidgetRef,
        side: impl Fn(bool) -> bool + 'static,
        paint_offset: f64,
    ) -> WidgetRef {
        NotificationListener::<OverscrollIndicatorNotification>::new(child)
            .on_notification(move |_app, notification| {
                if side(notification.leading) {
                    notification.paint_offset.set(paint_offset);
                }
                false
            })
            .into_widget()
    }

